"""Builds Denver Lang's clinical sample records from his Synthea bundle.

The patient is Denver Lang, born 1947, from Synthea's published sample data
(https://github.com/synthetichealth/synthea-sample-data, FHIR R4). Synthea
generates whole synthetic lives, so every record belongs to the same person
and spans decades: type 2 diabetes and hypertension from 1987, ischemic heart
disease with bypass surgery in 1997, and yearly care through 2026.

The script writes one PDF per selected visit note, one PDF of lab results per
year, one PNG photo of a lab printout for the ``needs_text`` path, and a
manifest with each file's title and record date.

Usage:
    uv run --with reportlab python scripts/make_sample_records.py BUNDLE.json
"""

from __future__ import annotations

import base64
import collections
import dataclasses
import json
import pathlib
import re
import sys
import textwrap

from reportlab.lib import pagesizes
from reportlab.lib import styles
from reportlab import platypus

import sample_rendering

OUT = pathlib.Path(
    __file__).resolve().parent.parent / "src/stellis/sample_records"
MANIFEST = "manifest-clinical.json"
SOURCE = ("Synthetic patient generated by Synthea (synthetichealth/synthea, "
          "Apache License 2.0). Not a real person.")
FIRST_YEAR = 2016
PHOTO_YEAR = 2025
# Encounter types become visit titles; types not listed here are left out.
VISIT_TITLES = {
    "General examination of patient (procedure)": "Annual exam",
    "Encounter for check up (procedure)": "Check-up",
    "Encounter for problem (procedure)": "Problem visit",
    "Encounter for symptom (procedure)": "Symptom visit",
    "Urgent care clinic (environment)": "Urgent care visit",
    "Emergency room admission (procedure)": "Emergency visit",
    "Hospital admission (procedure)": "Hospital admission",
}
ROUTINE = frozenset({"Annual exam", "Check-up"})
LAB_PANELS = frozenset({
    "Lipid panel with direct LDL - Serum or Plasma",
    "Basic metabolic panel - Blood",
    "Comprehensive metabolic 2000 panel - Serum or Plasma",
    "CBC panel - Blood by Automated count",
})
# Synthea holds an adult's weight constant, at 86.1 kg for Denver from 2017
# on. These weights follow his outside records instead: about 87 kg in 2019,
# an 8 kg gain to 95 kg by early 2024, then dietitian-led loss to 86 kg.
# Keyed by visit date; other visits keep Synthea's value.
WEIGHT_KG = {
    "2017-02-02": 86.4,
    "2018-02-08": 86.8,
    "2018-08-23": 86.9,
    "2019-02-14": 87.0,
    "2020-02-20": 88.9,
    "2021-02-25": 90.8,
    "2022-03-03": 92.4,
    "2023-03-09": 93.9,
    "2024-03-14": 95.2,
    "2025-03-20": 88.1,
    "2026-03-26": 86.3,
}
# Vital sign observations shown in visit notes, in display order.
VITAL_LABELS = {
    "Body Weight": "Weight",
    "Body mass index (BMI) [Ratio]": "BMI",
    "Blood pressure panel with all children optional": "Blood pressure",
    "Heart rate": "Pulse",
    "Respiratory rate": "Respiratory rate",
}
# Synthea appends digits to generated names, such as "Denver542".
_NAME_DIGITS = re.compile(r"\b([A-Z][a-z]+)\d+\b")


@dataclasses.dataclass(frozen=True)
class Visit:
    """One encounter's clinical note."""
    date: str
    title: str
    note: str
    vitals: tuple[str, ...] = ()


@dataclasses.dataclass(frozen=True)
class LabResult:
    """One measured value in a lab panel."""
    panel: str
    test: str
    value: str
    unit: str


def _resource_id(reference: str) -> str:
    return reference.split(":")[-1].split("/")[-1]


def _readable(text: str) -> str:
    return _NAME_DIGITS.sub(r"\1", text)


def _vital_lines(observations: list[dict], date: str) -> tuple[str, ...]:
    """Formats an encounter's vital signs, one "Label: value unit" each."""
    values: dict[str, str] = {}
    height_m = None
    for observation in observations:
        name = observation["code"]["text"]
        if name == "Body Height":
            height_m = observation["valueQuantity"]["value"] / 100
        if name not in VITAL_LABELS:
            continue
        if "component" in observation:
            parts = {
                item["code"]["text"]: item["valueQuantity"]["value"]
                for item in observation["component"]
            }
            values[name] = (f"{parts['Systolic Blood Pressure']:.0f}/"
                            f"{parts['Diastolic Blood Pressure']:.0f} mmHg")
        else:
            quantity = observation["valueQuantity"]
            values[name] = f"{quantity['value']:g} {quantity['unit']}"
    if date in WEIGHT_KG and "Body Weight" in values:
        values["Body Weight"] = f"{WEIGHT_KG[date]:g} kg"
        if height_m:
            bmi = WEIGHT_KG[date] / height_m**2
            values["Body mass index (BMI) [Ratio]"] = f"{bmi:.1f} kg/m2"
    return tuple(
        f"{VITAL_LABELS[name]}: {values[name]}".replace("/min", " per minute")
        for name in VITAL_LABELS
        if name in values)


def select_visits(resources: list[dict]) -> list[Visit]:
    """Picks the visit notes for the sample record.

    Args:
        resources: Every resource in the patient's FHIR bundle.

    Returns:
        From ``FIRST_YEAR`` on, the first routine visit of each year and every
        acute visit; before that, hospital admissions only. Oldest first.
    """
    encounters = {
        item["id"]: item
        for item in resources
        if item["resourceType"] == "Encounter"
    }
    vitals_by_encounter: dict[str, list[dict]] = collections.defaultdict(list)
    for item in resources:
        if item["resourceType"] == "Observation" and "encounter" in item:
            vitals_by_encounter[_resource_id(
                item["encounter"]["reference"])].append(item)
    visits: list[Visit] = []
    routine_years: set[str] = set()
    notes = sorted((item for item in resources
                    if item["resourceType"] == "DocumentReference"),
                   key=lambda item: item["date"])
    for note in notes:
        encounter = encounters[_resource_id(
            note["context"]["encounter"][0]["reference"])]
        title = VISIT_TITLES.get(encounter["type"][0]["text"])
        date = note["date"][:10]
        if title is None:
            continue
        if date[:4] < str(FIRST_YEAR) and title != "Hospital admission":
            continue
        if title in ROUTINE:
            if date[:4] in routine_years:
                continue
            routine_years.add(date[:4])
        text = base64.b64decode(note["content"][0]["attachment"]["data"])
        vitals = _vital_lines(vitals_by_encounter[encounter["id"]], date)
        visits.append(
            Visit(date, title,
                  _readable(text.decode()).strip(), vitals))
    return visits


def select_labs(resources: list[dict]) -> dict[str, list[LabResult]]:
    """Collects each year's last lab panels from ``FIRST_YEAR`` on.

    Args:
        resources: Every resource in the patient's FHIR bundle.

    Returns:
        A map from the collection date to that day's results. Each year keeps
        only its latest collection date.
    """
    observations = {
        item["id"]: item
        for item in resources
        if item["resourceType"] == "Observation"
    }
    by_date: dict[str, list[LabResult]] = collections.defaultdict(list)
    for report in resources:
        if (report["resourceType"] != "DiagnosticReport" or
                report["code"].get("text") not in LAB_PANELS):
            continue
        date = report["effectiveDateTime"][:10]
        if date[:4] < str(FIRST_YEAR):
            continue
        for reference in report.get("result", []):
            observation = observations[_resource_id(reference["reference"])]
            quantity = observation.get("valueQuantity", {})
            if "value" not in quantity:
                continue
            by_date[date].append(
                LabResult(report["code"]["text"], observation["code"]["text"],
                          f"{quantity['value']:.1f}", quantity.get("unit", "")))
    latest = {}
    for date in sorted(by_date):
        latest[date[:4]] = date
    return {date: by_date[date] for date in sorted(latest.values())}


def _escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _write_pdf(path: pathlib.Path, title: str, blocks: list) -> None:
    sheet = styles.getSampleStyleSheet()
    story = [
        platypus.Paragraph(_escape(title), sheet["Title"]),
        platypus.Paragraph("Patient: Denver Lang, born 1947-08-14",
                           sheet["Normal"]),
        platypus.Spacer(0, 12),
        *blocks,
        platypus.Spacer(0, 12),
        platypus.Paragraph(SOURCE, sheet["Italic"]),
    ]
    document = platypus.SimpleDocTemplate(str(path),
                                          pagesize=pagesizes.LETTER,
                                          title=title,
                                          author="Synthea sample record",
                                          invariant=True)
    document.build(story)


def _note_blocks(note: str) -> list:
    """Turns a Synthea Markdown note into headings and paragraphs."""
    sheet = styles.getSampleStyleSheet()
    blocks = []
    for line in note.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#"):
            blocks.append(
                platypus.Paragraph(_escape(line.lstrip("# ")),
                                   sheet["Heading3"]))
        else:
            blocks.append(platypus.Paragraph(_escape(line), sheet["BodyText"]))
    return blocks


def _vital_blocks(vitals: tuple[str, ...]) -> list:
    """Renders a visit's vital signs as a heading and one line each."""
    if not vitals:
        return []
    sheet = styles.getSampleStyleSheet()
    return [platypus.Paragraph("Vital Signs", sheet["Heading3"])] + [
        platypus.Paragraph(_escape(line), sheet["BodyText"]) for line in vitals
    ]


def _lab_lines(results: list[LabResult]) -> list[str]:
    lines = []
    panel = None
    for result in results:
        if result.panel != panel:
            panel = result.panel
            lines.append(panel)
        lines.append(f"{result.test}: {result.value} {result.unit}")
    return lines


def _lab_blocks(results: list[LabResult]) -> list:
    sheet = styles.getSampleStyleSheet()
    panels = {result.panel for result in results}
    return [
        platypus.Paragraph(_escape(line),
                           sheet["Heading3" if line in panels else "BodyText"])
        for line in _lab_lines(results)
    ]


def _photo_lines(title: str, results: list[LabResult]) -> list[str]:
    lines = [title, "Patient: Denver Lang", ""]
    for line in _lab_lines(results):
        lines += textwrap.wrap(line, 70)
    return lines + ["", *textwrap.wrap(SOURCE, 70)]


def main(bundle_path: str) -> None:
    """Writes the sample files and their manifest."""
    bundle = json.loads(pathlib.Path(bundle_path).read_text())
    resources = [entry["resource"] for entry in bundle["entry"]]
    OUT.mkdir(exist_ok=True)
    sample_rendering.replace_outputs(OUT, MANIFEST)
    records = []
    for visit in select_visits(resources):
        slug = visit.title.lower().replace(" ", "-").replace("_", "-")
        filename = f"{visit.date}-{slug}.pdf"
        _write_pdf(OUT / filename, f"{visit.title} {visit.date}",
                   _vital_blocks(visit.vitals) + _note_blocks(visit.note))
        records.append({
            "file": filename,
            "title": visit.title,
            "record_date": visit.date
        })
    for date, results in select_labs(resources).items():
        title = f"Lab results {date}"
        if date.startswith(str(PHOTO_YEAR)):
            filename = f"{date}-lab-results-photo.png"
            sample_rendering.write_photo(OUT / filename,
                                         _photo_lines(title, results))
        else:
            filename = f"{date}-lab-results.pdf"
            _write_pdf(OUT / filename, title, _lab_blocks(results))
        records.append({
            "file": filename,
            "title": "Lab results",
            "record_date": date
        })
    records.sort(key=lambda record: record["record_date"])
    manifest = {"patient": "Denver Lang", "source": SOURCE, "records": records}
    (OUT / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Wrote {len(records)} records to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
